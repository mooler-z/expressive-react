// Builds the `expressive-react` npm package from the same sources the shadcn registry ships:
//   src/components/ui/*.tsx · src/hooks/*.ts · src/lib/utils.ts · src/styles/expressive.css
//
// 1. Stage every module flat into .stage/src, rewriting `@/…` imports to relative `./x.js` paths
// 2. Generate an index barrel
// 3. tsc → dist/*.js + dist/*.d.ts (one ESM file per module, "use client" kept)
// 4. dist/styles.css = the theme, plus an @source line so Tailwind scans the package automatically
import { execFileSync } from "node:child_process"
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { basename, dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), "..")
const repo = join(pkgDir, "..", "..")
const stage = join(pkgDir, ".stage")
const out = join(pkgDir, "dist")

const SOURCES = [
  { dir: "src/components/ui", alias: "@/components/ui/" },
  { dir: "src/hooks", alias: "@/hooks/" },
]

rmSync(stage, { recursive: true, force: true })
rmSync(out, { recursive: true, force: true })
mkdirSync(join(stage, "src"), { recursive: true })

// --- 1. stage + rewrite imports ------------------------------------------------------------
const modules = []
const files = [
  ...SOURCES.flatMap(({ dir }) =>
    readdirSync(join(repo, dir))
      .filter((f) => /\.(tsx?|ts)$/.test(f))
      .map((f) => join(repo, dir, f)),
  ),
  join(repo, "src/lib/utils.ts"),
]

const seen = new Map()
for (const file of files) {
  const name = basename(file).replace(/\.tsx?$/, "")
  if (seen.has(name)) throw new Error(`module name clash: ${name} (${seen.get(name)} and ${file})`)
  seen.set(name, file)
  modules.push(name)

  const source = readFileSync(file, "utf8").replace(/(from\s+|import\(\s*)(["'])(@\/[^"']+)\2/g, (_, lead, q, spec) => {
    for (const { alias } of SOURCES) if (spec.startsWith(alias)) return `${lead}${q}./${spec.slice(alias.length)}.js${q}`
    if (spec === "@/lib/utils") return `${lead}${q}./utils.js${q}`
    throw new Error(`${file}: unsupported import "${spec}" — shipped code may only import @/components/ui, @/hooks and @/lib/utils`)
  })
  if (/from\s+["']\.\.?\//.test(source.replace(/from\s+["']\.\/[^"']+\.js["']/g, "")))
    throw new Error(`${file}: relative imports must point at sibling modules`)
  writeFileSync(join(stage, "src", basename(file)), source)
}

// --- 2. barrel ----------------------------------------------------------------------------
modules.sort()
writeFileSync(
  join(stage, "src", "index.ts"),
  "// Generated by scripts/build.mjs — every module, re-exported. Prefer subpath imports (expressive-react/button) for the smallest bundles.\n" +
    modules.map((m) => `export * from "./${m}.js"`).join("\n") +
    "\n",
)

// --- 3. compile ---------------------------------------------------------------------------
writeFileSync(
  join(stage, "tsconfig.json"),
  JSON.stringify(
    {
      compilerOptions: {
        target: "ES2022",
        lib: ["ES2022", "DOM", "DOM.Iterable"],
        module: "ESNext",
        moduleResolution: "bundler",
        jsx: "react-jsx",
        declaration: true,
        strict: true,
        skipLibCheck: true,
        isolatedModules: true,
        verbatimModuleSyntax: true,
        rootDir: "src",
        outDir: out,
        types: [],
      },
      include: ["src"],
    },
    null,
    2,
  ),
)
// The workspace's own TypeScript (its package `exports` hide bin/, so use the installed binary)
const tsc = join(repo, "node_modules", ".bin", process.platform === "win32" ? "tsc.cmd" : "tsc")
try {
  execFileSync(tsc, ["-p", join(stage, "tsconfig.json")], { stdio: "inherit", cwd: repo })
} catch {
  console.error("\n✗ tsc failed (staged sources are in packages/expressive-react/.stage)")
  process.exit(1)
}

// "use client" must survive compilation for React Server Components frameworks.
for (const m of modules) {
  const src = readFileSync(seen.get(m), "utf8")
  const js = readFileSync(join(out, `${m}.js`), "utf8")
  if (/^["']use client["']/.test(src.trimStart()) && !/^["']use client["']/.test(js.trimStart()))
    throw new Error(`${m}.js lost its "use client" directive`)
}

// --- 4. styles ----------------------------------------------------------------------------
const theme = readFileSync(join(repo, "src/styles/expressive.css"), "utf8")
writeFileSync(
  join(out, "styles.css"),
  `/* expressive-react · import after Tailwind:  @import "tailwindcss";  @import "expressive-react/styles.css"; */\n` +
    `/* Tailwind ignores node_modules by default; this registers the package's components as a class source. */\n` +
    `@source "./";\n\n` +
    theme,
)

// LICENSE travels with the package
if (existsSync(join(repo, "LICENSE"))) cpSync(join(repo, "LICENSE"), join(pkgDir, "LICENSE"))

rmSync(stage, { recursive: true, force: true })
console.log(`✓ expressive-react · ${modules.length} modules + index + styles.css → dist/`)
