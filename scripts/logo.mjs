// The Expressive React mark. Run `node scripts/logo.mjs` after changing anything here; it writes
// public/logo.svg, public/logo-dark.svg, public/favicon.svg (follows the OS color scheme) and
// src/docs/site/logo-paths.ts (paths and colors for the inline <LogoMark> in logo.tsx).
//
// Geometry: a regular {8/3} octagram drawn as one ribbon, split into four tonal runs where it
// crosses the vertical axis (lavender, violet, indigo, plum). Corners are filleted on the
// centerline with radius band/2, so the outside corner radius is one band and the inside is sharp.
// The nucleus is the shape library's clover4 (src/components/ui/shape.tsx), turned 45°.
import { writeFileSync } from "node:fs"

const C = 50 // viewBox 0 0 100 100
const E = 48 // half-extent of the ribbon's outer edge
const BAND = +(0.2355 * E).toFixed(2)
const r = BAND / 2
const R = 1.1352 * E // star circumradius that puts the rounded tips at E
const a = R * Math.cos((3 * Math.PI) / 8)
const b = R * Math.cos(Math.PI / 8)

const f = (n) => +n.toFixed(2)
const pt = (x, y) => [C + x, C + y]
const [V1, V2, V3, V4, V5, V6, V7, V8] = [pt(a, -b), pt(a, b), pt(-b, -a), pt(b, -a), pt(-a, b), pt(-a, -b), pt(b, a), pt(-b, a)]
const X = pt(0, b - a) // where the two lower diagonals cross the axis
const top = pt(0, -a)
const bottom = pt(0, a)

/** Open polyline with every interior corner filleted. */
function run(pts) {
  let d = `M${f(pts[0][0])} ${f(pts[0][1])}`
  for (let i = 1; i < pts.length - 1; i++) {
    const [p, v, q] = [pts[i - 1], pts[i], pts[i + 1]]
    const u1 = [p[0] - v[0], p[1] - v[1]]
    const u2 = [q[0] - v[0], q[1] - v[1]]
    const l1 = Math.hypot(...u1)
    const l2 = Math.hypot(...u2)
    const t = r / Math.tan(Math.acos((u1[0] * u2[0] + u1[1] * u2[1]) / (l1 * l2)) / 2)
    const s = [v[0] + (u1[0] / l1) * t, v[1] + (u1[1] / l1) * t]
    const e = [v[0] + (u2[0] / l2) * t, v[1] + (u2[1] / l2) * t]
    const sweep = u1[0] * u2[1] - u1[1] * u2[0] < 0 ? 1 : 0
    d += `L${f(s[0])} ${f(s[1])}A${f(r)} ${f(r)} 0 0 ${sweep} ${f(e[0])} ${f(e[1])}`
  }
  const z = pts.at(-1)
  return `${d}L${f(z[0])} ${f(z[1])}`
}

const RUNS = {
  plum: run([X, V5, V6, V7, bottom]),
  indigo: run([top, V4, X]),
  violet: run([X, V3, top]),
  lavender: run([bottom, V8, V1, V2, X]),
}

const N = 96
const RC = 0.205 * E
const CLOVER = `M${Array.from({ length: N }, (_, i) => {
  const t = (i / N) * Math.PI * 2
  const rr = (0.74 - 0.26 * Math.cos(4 * t)) * RC
  return `${f(C + rr * Math.cos(t))} ${f(C + rr * Math.sin(t))}`
}).join("L")}Z`

// Plum, indigo and violet multiply where they cross; lavender is woven over the top.
const LIGHT = { plum: "#5E2D77", indigo: "#5D459E", violet: "#A57DE0", lavender: "#D0BCFF", lavenderOpacity: 0.7, clover: "#F87878" }
const DARK = { plum: "#B58AD6", indigo: "#9A86E8", violet: "#C9AEF6", lavender: "#DCC8FF", lavenderOpacity: 0.92, clover: "#FF8A80" }

const css = (c) =>
  `.p{stroke:${c.plum}}.i{stroke:${c.indigo}}.v{stroke:${c.violet}}.l{stroke:${c.lavender};opacity:${c.lavenderOpacity}}.k{fill:${c.clover}}`
const svg = (style) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><title>Expressive React</title><style>${style}</style>` +
  `<g fill="none" stroke-width="${BAND}" style="isolation:isolate">` +
  `<path class="p" d="${RUNS.plum}" style="mix-blend-mode:multiply"/>` +
  `<path class="i" d="${RUNS.indigo}" style="mix-blend-mode:multiply"/>` +
  `<path class="v" d="${RUNS.violet}" style="mix-blend-mode:multiply"/>` +
  `<path class="l" d="${RUNS.lavender}"/></g><path class="k" d="${CLOVER}"/></svg>\n`

const themeClasses = (c, v = "") =>
  Object.entries(c)
    .map(([k, val]) => `${v}[--logo-${k.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)}:${val}]`)
    .join(" ")

writeFileSync("public/logo.svg", svg(css(LIGHT)))
writeFileSync("public/logo-dark.svg", svg(css(DARK)))
writeFileSync("public/favicon.svg", svg(`${css(LIGHT)}@media (prefers-color-scheme:dark){${css(DARK)}}`))
writeFileSync(
  "src/docs/site/logo-paths.ts",
  `// Generated by scripts/logo.mjs. Don't edit by hand.\n` +
    `export const LOGO_BAND = ${BAND}\n` +
    `export const LOGO_RUNS = ${JSON.stringify(RUNS, null, 2)} as const\n` +
    `export const LOGO_CLOVER = "${CLOVER}"\n` +
    // A literal class string, so Tailwind picks the custom properties up from this file.
    `export const LOGO_THEME =\n  "${themeClasses(LIGHT)} ${themeClasses(DARK, "dark:")}"\n`,
)
console.log("logo: public/logo.svg, public/logo-dark.svg, public/favicon.svg, src/docs/site/logo-paths.ts")
